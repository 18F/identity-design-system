if (output === '--check-sass') {
  /** @type {string[]} */
  const pages = JSON.parse(await readFile('docs/_data/nds_components.json', 'utf8'));
  const migrated = new Set(pages.map((page) => `docs/_components/${page}.md`));
  /** @param {string} dir */
  async function checkDirectory(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        await checkDirectory(path);
        continue;
      }
      if (!/\.(md|html|scss)$/.test(path) || entry.name === '_icon-assets.scss') continue;
      const text = await readFile(path, 'utf8');
      if (
        (migrated.has(path) || path.startsWith('docs/_includes/helpers/')) &&
        /(?:\/(?:material-icons|usa-icons(?:-bg)?)\/|\/sprite\.svg|data:image\/svg|<svg\b[^>]*>\s*<(?:path|g|circle)\b)/i.test(
          text,
        )
      )
        throw new Error(`Use a catalog icon, not inline or third-party artwork: ${path}`);
      for (const [, key] of text.matchAll(/nds-icons\/library\/([\w-]+)\.svg/g))
        if (!masters.has(key)) throw new Error(`Unknown catalog icon ${key}: ${path}`);
      for (const [, id] of text.matchAll(/nds-icons\/symbols\.svg#([\w-]+)/g))
        if (!symbols.includes(id)) throw new Error(`Missing NDS sprite symbol ${id}: ${path}`);
    }
  }
  for (const dir of [
    'src/scss/nds',
    'docs/_components',
    'docs/_embeds',
    'docs/_layouts',
    'docs/_includes',
  ])
    await checkDirectory(dir);
  process.exit(0);
}
const sprite = await Promise.all(
  symbols.map(async (key) => {
    const drawing = await svg(key, 'currentColor');
    const match = drawing.match(/viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>/);
    if (!match) throw new Error(`Missing SVG viewBox or drawing for symbol: ${key}`);
    const [, box, body] = match;
    return `<symbol id="${key}" viewBox="${box}" fill="none">${body}</symbol>`;
  }),
);
await emit('symbols.svg', `<svg xmlns="http://www.w3.org/2000/svg">${sprite.join('\n')}</svg>`);

const aliases = {
  expand_more: 'chevron-down',
  expand_less: 'chevron-up',
  navigate_next: 'chevron-right',
  navigate_before: 'chevron-left',
  navigate_far_before: 'chevron-left',
  navigate_far_next: 'chevron-right',
  add: 'plus-16',
  remove: 'minus',
  check_circle: 'check-circle',
  launch: 'external-link',
  calendar_today: 'calendar',
  unfold_more: 'chevron-down',
  arrow_back: 'arrow-right',
  close: 'close',
  error: 'error',
  info: 'info',
  warning: 'warning',
  search: 'search',
};
for (const [name, key] of Object.entries(aliases)) {
  let image = await svg(key);
  if (name === 'arrow_back')
    image = image
      .replace(/(<svg[^>]+>)/, '$1<g transform="translate(24 0) scale(-1 1)">')
      .replace('</svg>', '</g></svg>');
  // Date pickers distinguish year navigation (two chevrons) from month
  // navigation (one). Compose two instances of the same library drawing.
  if (name.startsWith('navigate_far_'))
    image = image.replace(
      /(<svg[^>]+>)([\s\S]+)<\/svg>/,
      '$1<g transform="translate(-4)">$2</g><g transform="translate(4)">$2</g></svg>',
    );
  await emit(`compat/usa-icons/${name}.svg`, image);
}
