import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

// USWDS requests these filenames internally. Only the NDS theme points here.
// A missing catalog drawing is a build failure, never a fallback to Material.
const source = new URL('../src/img/nds-icons/library/', import.meta.url);
/** @type {{ icons: { variants: { asset: string }[] }[] }} */
const { icons } = JSON.parse(await readFile(new URL('catalog.json', source), 'utf8'));
const masters = new Set(icons.flatMap(({ variants }) => variants.map(({ asset }) => asset)));
const output = process.argv[2];
if (!output) throw new Error('Expected the built assets/img/nds-icons directory');

/**
 * @param {string} key
 * @param {string} [ink]
 */
async function svg(key, ink) {
  if (!masters.has(key)) throw new Error(`Unknown NDS icon: ${key}`);
  const original = await readFile(new URL(`${key}.svg`, source), 'utf8');
  if (!ink) return original;
  if (!original.includes('fill="#000c1f"')) throw new Error(`Cannot recolor ${key}`);
  return original.replaceAll('fill="#000c1f"', `fill="${ink}"`);
}

/**
 * @param {string} path
 * @param {string} contents
 */
async function emit(path, contents) {
  const target = join(output, path);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, contents);
}

