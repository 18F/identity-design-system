// copying paths. Commit the resulting partial alongside its source SVGs.
if (output === '--sass' || output === '--check-sass') {
  const definitions = [
    ['check-white', 'checkmark', 'white'],
    ['minus-white', 'minus', 'white'],
    ['search-white', 'search', 'white'],
    ['error-dark', 'error-20', '#ad142b'],
    ['chevron-muted', 'chevron-down', '#000c1fa6'],
    ...[
      'info',
      'warning',
      'error',
      'check-circle',
      'arrow-up-from-line',
      'document',
      'loader-radial',
      'external-link',
      'not-visible-hide',
      'visible-show',
      'chevron-down',
      'close',
      'checkmark',
    ].map((key) => [key, key]),
  ];
  let partial = '// Generated by scripts/build-nds-icons.mjs --sass from the NDS icon catalog.\n';
  for (const [name, key, ink] of definitions) {
    const encoded = encodeURIComponent((await svg(key, ink)).trim()).replaceAll("'", '%27');
    partial += `$${name}: url('data:image/svg+xml,${encoded}');\n`;
  }
  const target = new URL('../src/scss/nds/_icon-assets.scss', import.meta.url);
  if (output === '--sass') await writeFile(target, partial);
  else if ((await readFile(target, 'utf8')) !== partial)
    throw new Error('Run node scripts/build-nds-icons.mjs --sass');
  if (output === '--sass') process.exit(0);
}

